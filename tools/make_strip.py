"""Build the driver strip's data from the approved design (tools/make_strip_mockups.py,
docs/design/driver_strip.png, radio_wave.gif - Grant, 10 Nov 2026):
  src/strip_img.asm  - the strip's fixed picture (rows 160-191, columns 0-23) and its
                       colours: drawn once at the start (start-up area)
  src/strip_data.asm - the small letters (3 x 5, 2 bytes each), the NOS icon, and the
                       crew chief's messages (kept in the buffer's bottom rows)"""
import os, re
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
src = open(os.path.join(HERE, 'make_strip_mockups.py')).read()
ns = {'__file__': os.path.join(HERE, 'make_strip_mockups.py')}
exec(src[:src.index('MSGS = ')], ns)                  # load(), strip(), the faces, the letters
src2 = src[src.index('# ---- small letters'):src.index('def stext')]
exec(src2, ns)
NOS, SMALL = ns['NOS'], ns['SMALL']
# the fixed picture: the strip with empty slots and an empty message box
bits, attr = ns['load']()
b, a = ns['strip'](())
b[169:183, 33:47] = 0                                 # slot 1 empty: the game draws the icon
b[160:192, 88:192] = 0                                # no bubble: the game draws it while the
b[160:192, 0:32] = 0                                  # crew chief talks (Grant)
for r in range(20, 24):
    for c in list(range(0, 4)) + list(range(11, 24)): a[r * 32 + c] = 0x30
# the layout review (Grant, 10 Nov 2026: "the faces at the bottom are too blocky"): the two
# faces at their own 16 x 16 size, each in a 2 x 2 cell panel (rows 21-22): you in columns
# 1-2 on your red, the crew chief in columns 21-22 on blue
YOU, CREW = ns['YOU'], ns['CREW']
for j in range(16):
    for i in range(16):
        b[168 + j, 8 + i] = YOU[j][i] == 'X'
        b[168 + j, 168 + i] = CREW[j][i] == 'X'
for r in (21, 22):
    for c in (1, 2): a[r * 32 + c] = 0x57
    for c in (21, 22): a[r * 32 + c] = 0x4F
# the bubble's tail: a white point in the chief's panel (column 21, rows 172-179). It is
# drawn over the left of his face, so the game keeps those 8 bytes of the face to put back
TAIL = [0x80, 0xC0, 0xE0, 0xF0, 0xF0, 0xE0, 0xC0, 0x80]
FACE_L = [int(''.join('1' if v == 'X' else '0' for v in CREW[j][:8]), 2) for j in range(4, 12)]
with open(os.path.join(ROOT, 'src', 'strip_img.asm'), 'w') as f:
    f.write('; GENERATED by tools/make_strip.py - the driver strip, drawn once at the start\n')
    f.write('; rows 160..191, 24 bytes each (columns 0-23), then 4 rows x 24 colours\nstrip_img:\n')
    for y in range(160, 192):
        row = np.packbits(b[y, 0:192])
        f.write('        defb ' + ','.join('0x%02X' % v for v in row) + '\n')
    f.write('strip_attr:\n')
    for r in range(20, 24):
        f.write('        defb ' + ','.join('0x%02X' % a[r * 32 + c] for c in range(24)) + '\n')
# the letters the game uses: A-Z then ! . - ' (a space is just a gap)
CH = [chr(c) for c in range(ord('A'), ord('Z') + 1)] + ['!', '.', '-', "'"]
def pack(g):
    v = int(g.replace('X', '1').replace('.', '0') + '0', 2)    # 15 bits + 0, top-left first
    return v >> 8, v & 255
NOSA = open(os.path.join(HERE, 'face_art.txt')).read()
nos = re.search(r'== NOS face ==\n((?:[X.]{16}\n){16})', NOSA).group(1).split()
ys = [y for y in range(16) if 'X' in nos[y]]
MSGS = [('M_LUCK', 'GOOD LUCK!|SPACE FOR NOS'),       # the green light (stage 2 adds the NOS)
        ('M_PASS', 'GREAT MOVE!|NICE PASS'),           # you overtook
        ('M_P1', 'P1!|HOLD HIM OFF'),                  # you took the lead
        ('M_LOST', 'STAY CALM|GET HIM BACK'),          # you lost a place
        ('M_PUSH', 'PUSH! PUSH!|HE IS CLOSE'),         # second, close to the leader
        ('M_BEST', 'SUPERB LAP!|FASTEST YET'),         # your lap is the best yet
        ('M_HIT', 'GET IT|TOGETHER!'),                 # you hit the O's
        ('M_LAST', 'LAST LAP!|BRING IT HOME'),         # starting the last lap
        ('M_WIN', 'GET IN THERE!|YOU WON!'),           # you won
        ('M_DONE', 'WELL DRIVEN!'),                    # you finished, not first
        ('M_NOS', 'NOS READY!|SPACE TO BOOST'),        # you picked up a canister
        ('M_BOOST', 'NOS!|GO GO GO'),                  # you fired it
        ('M_SETUP', 'PICK TWO UPGRADES|KEYS ONE TWO THREE')]   # before the start: set your car up                  # you fired it           # you finished, not first
# the data goes in the free ends of the buffer's bottom-row strips: BUFF and BUFH
# whole, the ends of BUFE (after the row index) and BUFG (after the waypoints)
_nwp = int(re.search(r'NWP\s+equ\s+(\d+)', open(os.path.join(ROOT, 'src', 'waypoints.asm')).read()).group(1))
_maph = int(re.search(r'MAPH\s+equ\s+(\d+)', open(os.path.join(ROOT, 'src', 'world.asm')).read()).group(1))
# (154, not 160: the last 6 bytes of each strip are where the interrupt's pushes land when it
# arrives just as the cloth fill finishes a line at the start of the buffer's last third)
AREAS = [('F', 'BUFF', 154), ('H', 'BUFH', 154), ('E', 'BUFE', 154 - 2 * _maph), ('G', 'BUFG', 154),   # (the waypoints: in the program)
         ('T', 'TOPMEM', 16)]                          # (T: a few bytes at the top of memory)
out = {k: [] for k, _, _ in AREAS}; used = {k: 0 for k, _, _ in AREAS}
def put(k, text, n): out[k].append(text); used[k] += n
put('F', "; the small letters, 3 x 5: 15 bits each, top-left first (A-Z ! . - ')\nlfont_src:\n", 0)
for c in CH: put('F', '        defb 0x%02X,0x%02X   ; %s\n' % (pack(SMALL[c]) + (c,)), 2)
put('F', '; the NOS icon for a slot: %d rows, 2 bytes each (its byte pair centred)\nnos_icon_src:\n' % len(ys), 0)
for y in ys:
    v = int(nos[y].replace('X', '1').replace('.', '0'), 2)
    put('F', '        defb 0x%02X,0x%02X\n' % (v >> 8, v & 255), 2)
put('F', 'NOS_ROWS equ %d\n' % len(ys), 0)
used['F'] += 2 * len(MSGS)                           # (the index, written below)
where = {}
for i, (n, t) in enumerate(MSGS):
    for k, _, cap in AREAS:
        if used[k] + len(t) + 1 <= cap:
            put(k, '%s equ %d\n%s_t:\n        db "%s",0\n' % (n, i, n, t), len(t) + 1); where[n] = k; break
    else:
        raise SystemExit('no room for message %s' % n)
put('G', "; the bubble's tail over the chief's face (column 21, rows 172-179): shown, then gone\nbb_tail_src:\n        defb %s\n        defb %s\n"
    % (','.join('0x%02X' % (t | f) for t, f in zip(TAIL, FACE_L)), ','.join('0x%02X' % f for f in FACE_L)), 16)
SEC = {'F': ('buff_src', 'BUFF'), 'H': ('bufh_src', 'BUFH'), 'E': ('bufe_src', 'BUFE'), 'G': ('bufg_src', 'BUFG'), 'T': ('high_src', 'TOPMEM')}
out['F'].insert(len(out['F']) - sum(1 for n in where if where[n] == 'F'),
    "; the crew chief's messages, by number (their addresses once copied): lines split\n; by |, ended by 0\nmsg_index_src:\n" +
    ''.join('        dw %s_t - %s + %s\n' % (n, SEC[where[n]][0], SEC[where[n]][1]) for n, _ in MSGS))
for k, base, cap in AREAS:
    # each area is assembled where the program loads it, then copied to its strip:
    # its labels are turned into the strip's addresses with an offset (see racer.asm)
    with open(os.path.join(ROOT, 'src', 'strip_%s.asm' % k.lower()), 'w') as f:
        f.write('; GENERATED by tools/make_strip.py - copied to %s at the start (%d of %d bytes)\n' % (base, used[k], cap))
        f.write(''.join(out[k]))
print('strip data bytes:', used)
