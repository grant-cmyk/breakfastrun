"""UPPER=1 (the breakfast fast tapes with LOOP=1; Grant, 22 Nov 2026, the memory hunt's group A): tables moved up above
the looped screen-copy routine, into the 5,571 bytes it frees (UP_AT = HP = COPIER + 0x200, to HIMEM). pasmo has no PHASE,
so each table is assembled after the start-up area (up_src, racer.asm) under a renamed label (name_u) and start_once
copies the block up first thing; src/up_equs.asm gives each table's own name its address up there.
Usage: python3 tools/make_up.py file.asm [file.asm ...]   (MAPDAT: put before minimap.asm - its ink and dots)
Writes src/up_data.asm and src/up_equs.asm."""
import os, re, sys
SRC = os.environ.get('UP_SRC') or os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')   # (build.sh: the build's own copy)
data, equs = ['; GENERATED by tools/make_up.py - the tables kept above the looped copy routine (copied up by start_once)\n'], \
             ['; GENERATED by tools/make_up.py - the moved tables\' names, at their places above the copy routine\n']
for f in sys.argv[1:]:
    s = open(os.path.join(SRC, f)).read()
    if f == 'minimap.asm': s = 'MAPDAT:\n' + s
    names = re.findall(r'^([A-Za-z_][A-Za-z0-9_]*):', s, re.M)
    for n in names:
        s = re.sub(r'^%s:' % n, '%s_u:' % n, s, flags=re.M)
        equs.append('        if defined %s_u\n%-16s equ UP_AT + %s_u - up_src\n        endif\n' % (n, n, n))   # (a name in an IF that is off is not there)
    data.append('; ---- %s\n' % f + s + '\n')
open(os.path.join(SRC, 'up_data.asm'), 'w').write(''.join(data))
open(os.path.join(SRC, 'up_equs.asm'), 'w').write(''.join(equs))
print('make_up: %d files, %d names moved up' % (len(sys.argv) - 1, len(equs) - 1))
