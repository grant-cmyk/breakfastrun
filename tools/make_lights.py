"""The start lights (design L2, "pods" - Grant, 14 Nov 2026, docs/design/start_lights.png) and the
NOS canister for the play window, as data for the game: src/lights.asm.
The lamp shapes are those of tools/make_start_lights.py: a 14-pixel disc with a glint of housing
in it (lit), an empty ring (unlit), each in a black 16 x 16 box; the rail they hang from is one
cell row, 10 cells wide, hung from the window's frame."""
import os
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
def disc(r, cx=7.5, cy=7.5):
    y, x = np.mgrid[0:16, 0:16]
    return ((x - cx) ** 2 + (y - cy) ** 2 <= r * r).astype(np.uint8)
GLINT = (disc(4.6) - disc(3.4)) * (np.mgrid[0:16, 0:16][0] < 7) * (np.mgrid[0:16, 0:16][1] < 7)
LAMP = disc(6.9) * (1 - GLINT)
RING = disc(6.9) - disc(5.6)
CAN = ["..XXX..", "...X...", "..XXX..", ".XXXXX.", "X.....X", "XXXXXXX", "XXXXXXX", "X.....X", "X.....X", ".XXXXX."]
def rows16(a): return [(int(''.join(map(str, r[:8])), 2), int(''.join(map(str, r[8:])), 2)) for r in a]
with open(os.path.join(ROOT, 'src', 'lights.asm'), 'w') as f:
    f.write('; GENERATED by tools/make_lights.py - the start lights (L2, the pods) and the NOS canister\n')
    for name, art, what in (('lt_lamp', LAMP, 'a lamp lit: 16 rows x 2 bytes, ink the lamp, paper its black box'), ('lt_ring', RING, 'a lamp not lit: an empty ring')):
        f.write('%s:                        ; %s\n' % (name, what))
        for l, r in rows16(art): f.write('        defb 0x%02X,0x%02X\n' % (l, r))
    f.write('lt_rail:                        ; the rail, 10 cells wide: its 3 kinds of pixel row\n')
    f.write('        defb 0x03,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0xC0   ; rows 0-1: the two hangers up to the frame\n')
    f.write('        defb 0x0F,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xF0   ; rows 2-4: the rail\n')
    f.write('        defb 0x00,0x01,0x80,0x00,0x01,0x80,0x00,0x01,0x80,0x00   ; rows 5-7: a hanger down to each lamp\n')
    f.write('nos_can:                        ; a NOS canister, 7 x 10, in the top 7 bits of a byte\n')
    f.write('        defb ' + ','.join('0x%02X' % (int(r.replace('X', '1').replace('.', '0'), 2) << 1) for r in CAN) + '\n')
print('wrote src/lights.asm')
