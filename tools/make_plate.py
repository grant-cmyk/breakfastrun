"""The in-game place plate's data (Grant, 14 Nov 2026: "3 is good build 3" - the mock-up
tools/make_ingame_plate.py, version 3): src/plate.asm (in the program), src/plate_low.asm (in the
room under 0x8000) and src/plate_td.asm (in the table block at TD). Everything is a COLUMN strip:
the bytes of one byte-wide column, top to bottom, which pl_cut cuts out of the solid plate.
The small letters are make_ingame_plate.SMALL (3 x 5), two to a byte: bits 7-5 and 3-1."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
SMALL = {'0': '111 101 101 101 111', '1': '010 110 010 010 111', '2': '111 001 111 100 111', '3': '111 001 111 001 111',
         '/': '001 001 010 100 100', ' ': '000 000 000 000 000',
         'L': '100 100 100 100 111', 'A': '010 101 111 101 101', 'P': '110 101 110 100 100', 'F': '111 100 110 100 100',
         'I': '111 010 010 010 111', 'N': '110 101 101 101 101', '!': '010 010 010 000 010',
         'n': '000 110 101 101 101', 'd': '001 001 011 101 011', 'r': '000 101 110 100 100', 's': '000 011 110 001 110',
         't': '010 111 010 010 011', 'h': '100 100 110 101 101'}
def strip(text, x0, nbytes):
    """`text` in the small letters, its first letter's left edge at pixel x0: nbytes columns of 5 bytes."""
    rows = [[0] * (8 * nbytes) for _ in range(5)]
    for k, ch in enumerate(text):
        for j, r in enumerate(SMALL[ch].split()):
            for i, c in enumerate(r):
                if c == '1': rows[j][x0 + 4 * k + i] = 1
    return [[sum(rows[j][8 * b + i] << (7 - i) for i in range(8)) for j in range(5)] for b in range(nbytes)]
def db(f, name, cols, note):
    f.write('%s:                 ; %s\n' % (name, note))
    for c in cols: f.write('        db ' + ','.join('0x%02X' % v for v in c) + '\n')
S = os.path.join(HERE, '..', 'src')
with open(os.path.join(S, 'plate_low.asm'), 'w') as f:
    f.write('; GENERATED by tools/make_plate.py - the place plate\'s small letters (column strips, 5 rows)\n')
    db(f, 'pl_suf', [strip(s, 0, 1)[0] for s in ('st', 'nd', 'rd', 'th')], 'st, nd, rd, th')
    db(f, 'pl_lap', strip('LAP  /3', 0, 4), 'LAP n/3 without its figure: 4 columns')
with open(os.path.join(S, 'plate.asm'), 'w') as f:
    f.write('; GENERATED by tools/make_plate.py\n')
    db(f, 'pl_dig', [strip(d, 0, 1)[0] for d in '123'], 'the lap\'s figure: 1, 2, 3 (bits 7-5)')
with open(os.path.join(S, 'plate_td.asm'), 'w') as f:
    f.write('; GENERATED by tools/make_plate.py - kept in the table block at TD (racer.asm gives pl_msg)\n')
    db(f, 'pl_msg_src', strip('FINAL LAP!', 5, 6), 'FINAL LAP! from pixel 5: 6 columns')
print('plate data written')
