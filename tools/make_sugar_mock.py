for k in ICONS:
    ICONS[k] = ICONS[k].strip().split('\n'); assert len(ICONS[k]) == 16 and all(len(r) == 8 for r in ICONS[k]), k
CY, RED, BLUE, BG, FG = (0, 215, 215), (215, 0, 0), (0, 0, 215), (30, 30, 30), (235, 235, 235)
def font(n):
    for p in ('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',):
        if os.path.exists(p): return ImageFont.truetype(p, n)
    return ImageFont.load_default()
def icon(art, s):
    im = Image.new('RGB', (8 * s, 16 * s), CY); d = ImageDraw.Draw(im)
    for y, r in enumerate(art):
        for x, c in enumerate(r):
            if c == 'X': d.rectangle((x * s, y * s, x * s + s - 1, y * s + s - 1), fill=RED)
    return im
