"""The BREAKFAST RUN logo: 56 x 16 px (7 x 2 character cells), 1-bit first.
Value plan (one-bit-art skill):
  RUN        SOLID ink, italic slant for speed, a 2 px PAPER racing stripe cut
             through all three letters (negative space with room - rule 3a)
  BREAKFAST  LINE: a small 5x5 capital alphabet, one row of cells
  egg        the white is INK, the yolk is a PAPER hole (negative space), one
             ink pixel of shine in the yolk
Colour per 8x8 cell afterwards: BREAKFAST black on yellow; RUN bright red on
yellow; the egg's 2x2 cells bright white INK on yellow PAPER - so the yolk shows
yellow through the hole: two colours in each cell, as the Spectrum allows.
Writes build/logo.txt (a grid for one_bit_review.py) and src/logo.asm."""
import os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
W, H = 56, 16
g = [[0] * W for _ in range(H)]
F5 = {  # 5 x 5 capitals
 'B': ["####.", "#...#", "####.", "#...#", "####."], 'R': ["####.", "#...#", "####.", "#..#.", "#...#"],
 'E': ["#####", "#....", "####.", "#....", "#####"], 'A': [".###.", "#...#", "#####", "#...#", "#...#"],
 'K': ["#...#", "#..#.", "###..", "#..#.", "#...#"], 'F': ["#####", "#....", "####.", "#....", "#...."],
 'S': [".####", "#....", ".###.", "....#", "####."], 'T': ["#####", "..#..", "..#..", "..#..", "..#.."]}
x = 1
for ch in "BREAKFAST":
    for j, row in enumerate(F5[ch]):
        for i, c in enumerate(row):
            if c == '#': g[1 + j][x + i] = 1
    x += 6
# RUN: 8 px tall (was 16), in the second row of cells only, so the logo takes 2
# rows and the race order below has more room (Grant, 10 Nov 2026). Solid,
# italic, with the 1-px paper racing stripe through all three letters.
R = ["########.", "###...###", "###...###", "########.", ".........", "###.###..", "###..###.", "###...###"]
U = ["###...###", "###...###", "###...###", "###...###", ".........", "###...###", "#########", ".#######."]
N = ["###...###", "####..###", "#####.###", "###.#####", ".........", "###..####", "###...###", "###...###"]
for k, L in enumerate((R, U, N)):
    for y, row in enumerate(L):
        slant = (7 - y) // 3                         # italic: the top leans right
        for i, c in enumerate(row):
            if c == '#': g[8 + y][k * 12 + i + slant] = 1
# the egg, flattened to fit beside RUN: cells 5-6 of the second row - a lumpy
# white (overlapping blobs) with an off-centre yolk hole and one pixel of shine
blobs = [(47.5, 11.8, 7.2, 3.6), (51.5, 10.6, 3.8, 2.8), (43.5, 12.4, 3.6, 2.8)]
for y in range(8, 16):
    for x in range(40, 56):
        white = any(((x - bx) / rx) ** 2 + ((y - by) / ry) ** 2 <= 1 for bx, by, rx, ry in blobs)
        yolk = ((x - 47.0) / 2.6) ** 2 + ((y - 11.5) / 2.1) ** 2 <= 1
        g[y][x] = 1 if white and not yolk else 0
g[11][46] = 1                                         # shine: one pixel in the yolk
open(os.path.join(ROOT, 'build', 'logo.txt'), 'w').write('\n'.join(''.join('#' if v else '.' for v in r) for r in g) + '\n')
with open(os.path.join(ROOT, 'src', 'logo.asm'), 'w') as f:
    f.write('; GENERATED by tools/make_logo.py - the BREAKFAST RUN logo, 7 x 2 cells\n')
    f.write('; row by row, 7 bytes a pixel row, 16 rows; colours: logo_attr\nlogo_bits_src:\n')
    for r in g:
        f.write('        defb ' + ','.join('%%%s' % ''.join(str(v) for v in r[i:i + 8]) for i in range(0, W, 8)) + '\n')
    f.write('logo_attr_src:   ; 2 rows of 7 cells: black/yellow; red/yellow (RUN), white/yellow (egg)\n')
    f.write('        defb ' + ','.join(['0x30'] * 7) + '\n')
    f.write('        defb ' + ','.join(['0x72'] * 5 + ['0x77'] * 2) + '\n')
print('\n'.join(''.join('#' if v else '.' for v in r) for r in g))
