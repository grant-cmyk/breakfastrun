"""Generate the speed-critical straight-line code. Writes:
  src/gen_tiles.asm - tdraw_0..tdraw_7: draw one 8x8 tile into the buffer,
                      fully unrolled. The buffer is laid out like the screen,
                      so the next pixel row is INC H - except once per tile,
                      where the tile crosses into the next character row. That
                      line depends only on the camera's y AND 7, so there is
                      one version per value and the main loop picks it.
Why generated: the addresses and the crossing line are fixed, so writing them
out in full is fastest - and a script cannot make a typing mistake in them."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
BUF, SCREEN = 0xC000, 0x4000
WIN_Y, WIN_COL, WIN_W, WIN_H = 32, 4, 24, 128
BUF_ROW0, BUF_COL0 = 16, 2          # window (0,0) is buffer row 16, byte 2

def layout(base, row, byte):
    """Spectrum screen layout: base + 010 yy yyy / yyy xxxxx style."""
    return base | ((row & 0xC0) << 5) | ((row & 7) << 8) | ((row & 0x38) << 2) | byte

LINE = ['        ld a,(de)               ; tile byte', '        inc e', '        ld c,a',
        '        ld a,(bc)               ; part for the left byte', '        or (hl)', '        ld (hl),a',
        '        inc b', '        inc l', '        ld a,(bc)               ; part for the right byte',
        '        or (hl)', '        ld (hl),a', '        dec b', '        dec l']
CROSS = ['        ld a,l                  ; into the next character row:', '        add a,32',
         '        ld l,a', '        jr c,$+6                ; (carry: next third - H is already right)',
         '        ld a,h', '        sub 8', '        ld h,a']
with open(os.path.join(SRC, 'gen_tiles.asm'), 'w') as f:
    f.write('; GENERATED by tools/make_code.py - do not edit by hand\n')
    f.write('; tdraw_V: OR one tile (DE = its 8 bytes) into the buffer at HL, shifted\n')
    f.write('; through the tables at page B. V = camy AND 7: the tile crosses into the\n')
    f.write('; next character row after line V-1 (never, for V = 0).\n')
    for v in range(8):
        f.write('tdraw_%d:\n' % v)
        for i in range(8):
            f.write(LINE[0] + '\n' + LINE[1] + '\n')
            f.write('        or a                    ; a blank line: nothing to draw\n')
            f.write('        jr z,td%d_%d\n' % (v, i))
            f.write('\n'.join(LINE[2:]) + '\n')
            f.write('td%d_%d:\n' % (v, i))
            if i < 7:
                f.write('        inc h                   ; next pixel row\n')
                if v and i == v - 1:
                    f.write('\n'.join(CROSS) + '\n')
        f.write('        ret\n')
with open(os.path.join(SRC, 'tdtab.asm'), 'w') as f:                  # (kept at the top of memory)
    f.write('; GENERATED by tools/make_code.py - do not edit by hand\n')
    f.write('tdraw_table_src:\n' + ''.join('        dw tdraw_%d\n' % v for v in range(8)))
NCARS = 5
with open(os.path.join(SRC, 'gen_bumps.asm'), 'w') as f:
    # (a loop, not every pair written out: 60 bytes instead of 560 - room for the
    # driver strip; a pair's quick look costs ~70 T more, ~1 k T a picture)
    f.write("""; GENERATED by tools/make_code.py - do not edit by hand
; bump_all: every pair of cars (IX = the first, IY the one after it); only a
; pair within 11 pixels in x calls bump, which checks y and does the rest.
bump_all:
        ld ix,cars
        ld c,NCARS-1
ba_1:
        push ix
        pop iy
        ld b,c
ba_2:
        ld de,C_SIZE
        add iy,de
        ld l,(ix+C_X)
        ld h,(ix+C_X+1)
        ld e,(iy+C_X)
        ld d,(iy+C_X+1)
        or a
        sbc hl,de
        ld de,11
        add hl,de               ; 0..22 if within 11
        ld a,h
        or a
        jr nz,ba_3
        ld a,l
        cp 23
        jr nc,ba_3
        push bc
        push iy
        pop hl
        call bump               ; IX = car a, HL = car b
        pop bc
ba_3:
        djnz ba_2
        ld de,C_SIZE
        add ix,de
        dec c
        jr nz,ba_1
        ret
""")
print('wrote gen_tiles.asm and gen_bumps.asm')
