"""Generate the data stage 1 needs: 16 rotated car sprites, the track's
colour map, and the thrust table. Writes src/data.asm.
The car is a PLACEHOLDER drawn by maths - the real car gets a proper
one-bit-art design in stage 2."""
import math, os
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'data.asm')

def car_ink(x, y):
    """Car seen from above, nose pointing up (negative y). Units = pixels."""
    half = 2.4 if y < -4.0 else 3.5                           # narrower nose
    if abs(x) <= half and abs(y) <= 6.2:                      # body
        if abs(x) <= 2.4 and -3.6 <= y <= -1.0: return False  # big windscreen
        return True
    if 3.5 < abs(x) <= 4.7 and (2.4 <= abs(y) <= 5.2):        # wheels
        return True
    return False

def frame(n):
    th = n * 2 * math.pi / 16
    rows = []
    for py in range(16):
        bits = 0
        for px in range(16):
            hits = 0
            for sy in range(4):
                for sx in range(4):
                    dx = px + (sx + .5) / 4 - 8
                    dy = py + (sy + .5) / 4 - 8
                    # rotate the sample point back into car space
                    lx = dx * math.cos(th) + dy * math.sin(th)
                    ly = -dx * math.sin(th) + dy * math.cos(th)
                    hits += car_ink(lx, ly)
            if hits >= 8:
                bits |= 0x8000 >> px
        rows.append(bits)
    return rows

GRASS, ROAD, KERB_R, KERB_W, LINE = 0x20, 0x38, 0x10, 0x78, 0x30
def rr_inside(cx, cy, x0, y0, x1, y1, r):
    """Is cell centre inside a rounded rectangle?"""
    nx = min(max(cx, x0 + r), x1 - r)
    ny = min(max(cy, y0 + r), y1 - r)
    return (cx - nx) ** 2 + (cy - ny) ** 2 <= r * r

def track():
    road = [[False] * 32 for _ in range(24)]
    for y in range(24):
        for x in range(32):
            c = (x + .5, y + .5)
            road[y][x] = rr_inside(*c, 1, 1, 31, 23, 6) and not rr_inside(*c, 7, 7, 25, 17, 2.5)
    attrs = []
    for y in range(24):
        for x in range(32):
            if not road[y][x]:
                attrs.append(GRASS); continue
            edge = any(not road[y + dy][x + dx] if 0 <= y + dy < 24 and 0 <= x + dx < 32 else True
                       for dy in (-1, 0, 1) for dx in (-1, 0, 1))
            if x == 16 and y >= 17:
                attrs.append(LINE)                      # start / finish line
            elif edge:
                attrs.append(KERB_R if (x + y) % 2 else KERB_W)
            else:
                attrs.append(ROAD)
    return attrs

def w(v): return '0x%04X' % (v & 0xFFFF)

with open(OUT, 'w') as f:
    f.write('; GENERATED by tools/make_data.py - do not edit by hand\n\n')
    f.write('GRASS   equ 0x%02X\n\n' % GRASS)
    f.write('; thrust per frame for each of 16 headings: dx, dy in 8.8 fixed point\n')
    f.write('thrust_tab:\n')
    for n in range(16):
        th = n * 2 * math.pi / 16
        f.write('        dw %s,%s\n' % (w(round(64 * math.sin(th))), w(round(-64 * math.cos(th)))))
    f.write('\n; 16 car frames, 16x16 pixels, 2 bytes a row, frame 0 = facing up\n')
    f.write('sprites:\n')
    for n in range(16):
        f.write('; frame %d (%d degrees)\n' % (n, n * 22.5))
        for r in frame(n):
            f.write('        defb %%%s,%%%s\n' % (format(r >> 8, '08b'), format(r & 255, '08b')))
    f.write('\n; track colours: 32 x 24 attribute bytes, copied straight to 0x5800\n')
    f.write('track_attrs:\n')
    a = track()
    for y in range(24):
        f.write('        defb ' + ','.join('0x%02X' % v for v in a[y * 32:y * 32 + 32]) + '\n')

# preview of the 16 frames for a human to look at
try:
    from PIL import Image
    img = Image.new('RGB', (16 * 18 * 4, 18 * 4), (40, 120, 40))
    for n in range(16):
        for py, r in enumerate(frame(n)):
            for px in range(16):
                if r & (0x8000 >> px):
                    for a in range(4):
                        for b in range(4):
                            img.putpixel(((n * 18 + 1 + px) * 4 + a, (1 + py) * 4 + b), (0, 0, 0))
    img.save(os.path.join(HERE, '..', 'build', 'car_frames_preview.png'))
except ImportError:
    pass
print('wrote', os.path.normpath(OUT))
